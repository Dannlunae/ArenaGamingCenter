-- 003_pcs.sql — Gestión de PCs, actualizaciones y notas (ejecutar después de schema.sql)

-- ───────── PCs ─────────
-- estado: libre | en_uso | error | mantenimiento
create table pcs (
  id           bigint generated by default as identity primary key,
  nombre       text not null,
  ubicacion    text,
  orden        int not null default 0,
  estado       text not null default 'libre' check (estado in ('libre','en_uso','error','mantenimiento')),
  motivo       text,                                   -- obligatorio (por la app) en error / mantenimiento
  estado_desde timestamptz not null default now(),
  creado_at    timestamptz not null default now(),
  eliminado_at timestamptz
);
create unique index un_pc_nombre on pcs (lower(nombre)) where eliminado_at is null;

-- ───────── Catálogo de software actualizable ─────────
create table software (
  id     bigint generated by default as identity primary key,
  nombre text not null,
  tipo   text not null default 'juego' check (tipo in ('driver','juego','otro')),
  activo boolean not null default true,
  orden  int not null default 0
);
create unique index un_software_nombre on software (lower(nombre));

-- Estado de cada software en cada PC (independiente del estado de la PC)
create table pc_software (
  pc_id          bigint not null references pcs(id) on delete cascade,
  software_id    bigint not null references software(id) on delete cascade,
  estado         text not null default 'sin_revisar'
                 check (estado in ('sin_revisar','pendiente','actualizando','al_dia','error')),
  version        text,
  actualizado_at timestamptz,                          -- última vez que quedó al_dia
  nota           text,
  estado_desde   timestamptz not null default now(),
  primary key (pc_id, software_id)
);
create index ix_pc_software_estado on pc_software (software_id, estado);

-- ───────── Notas por PC ─────────
create table pc_notas (
  id           bigint generated by default as identity primary key,
  pc_id        bigint not null references pcs(id) on delete cascade,
  fecha        timestamptz not null default now(),
  comentario   text not null,
  autor_id     uuid references perfiles(id),
  resuelta     boolean not null default false,
  eliminado_at timestamptz
);
create index ix_pc_notas_pc on pc_notas (pc_id, fecha desc);

-- ───────── Datos iniciales: 3 software y 33 PCs ─────────
insert into software (nombre, tipo, orden)
select v.n, v.t, v.o
from (values ('Drivers','driver',1), ('Fortnite','juego',2), ('Valorant','juego',3)) as v(n,t,o)
where not exists (select 1 from software);

insert into pcs (nombre, orden)
select 'PC-' || lpad(n::text, 2, '0'), n from generate_series(1, 33) n
where not exists (select 1 from pcs);

insert into pc_software (pc_id, software_id)
select p.id, s.id from pcs p cross join software s
on conflict do nothing;

-- ───────── Auditoría (ahora también reconoce llaves compuestas de pc_software) ─────────
create or replace function auditar() returns trigger language plpgsql
security definer set search_path = public as $$
declare
  uid uuid := nullif(current_setting('app.usuario_id', true), '')::uuid;
  r   jsonb := case when tg_op = 'DELETE' then to_jsonb(old) else to_jsonb(new) end;
  rid text  := coalesce(r->>'id', nullif(concat_ws('-', r->>'arqueo_id', r->>'denominacion', r->>'pc_id', r->>'software_id'), ''));
begin
  if tg_op = 'INSERT' then
    insert into auditoria(tabla, registro_id, accion, usuario_id, despues)
    values (tg_table_name, rid, tg_op, uid, to_jsonb(new));
  elsif tg_op = 'UPDATE' then
    if to_jsonb(new) is distinct from to_jsonb(old) then
      insert into auditoria(tabla, registro_id, accion, usuario_id, antes, despues)
      values (tg_table_name, rid, tg_op, uid, to_jsonb(old), to_jsonb(new));
    end if;
  else
    insert into auditoria(tabla, registro_id, accion, usuario_id, antes)
    values (tg_table_name, rid, tg_op, uid, to_jsonb(old));
  end if;
  return null;
end $$;

create trigger aud_pcs         after insert or update or delete on pcs         for each row execute function auditar();
create trigger aud_software    after insert or update or delete on software    for each row execute function auditar();
create trigger aud_pc_software after insert or update or delete on pc_software for each row execute function auditar();
create trigger aud_pc_notas    after insert or update or delete on pc_notas    for each row execute function auditar();

-- RLS sin políticas: solo el backend accede
