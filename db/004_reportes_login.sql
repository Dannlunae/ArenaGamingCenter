-- 004_reportes_login.sql — límite de intentos de login + papelera completa (ejecutar después de 003)

create table login_intentos (
  id  bigint generated by default as identity primary key,
  ip  text not null,
  ok  boolean not null,
  at  timestamptz not null default now()
);
create index ix_login_intentos on login_intentos (ip, at desc);
alter table login_intentos enable row level security;

-- Vaciar papelera: ahora cubre yapes, comentarios, notas de PC, arqueos, turnos y PCs.
create or replace function purgar_papelera(dias int default 30) returns void
language sql as $$
  delete from yapes       where eliminado_at < now() - make_interval(days => dias);
  delete from comentarios where eliminado_at < now() - make_interval(days => dias);
  delete from pc_notas    where eliminado_at < now() - make_interval(days => dias);
  delete from arqueos     where eliminado_at < now() - make_interval(days => dias);
  delete from turnos t
   where t.eliminado_at < now() - make_interval(days => dias)
     and not exists (select 1 from yapes y       where y.turno_id = t.id)
     and not exists (select 1 from comentarios c where c.turno_id = t.id);
  delete from pcs where eliminado_at < now() - make_interval(days => dias);
$$;
