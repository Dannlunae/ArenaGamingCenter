-- schema.sql — Control de caja y yapes (Postgres / Supabase)
-- Unifica 001_init + 002_auditoria en un solo archivo, para una base nueva.
-- Las fechas se guardan en UTC (timestamptz). Los reportes por día/mes
-- se agrupan en hora de Lima: fecha AT TIME ZONE 'America/Lima'.

-- ───────── Usuarios (1 ahora; hasta 4 activos en total) ─────────
create table perfiles (
  id        uuid primary key,              -- = id del usuario en Supabase Auth
  nombre    text not null,
  rol       text not null default 'cajero' check (rol in ('admin','cajero')),
  activo    boolean not null default true,
  creado_at timestamptz not null default now()
);

create function limitar_usuarios() returns trigger language plpgsql as $$
begin
  if new.activo and (select count(*) from perfiles where activo and id <> new.id) >= 4 then
    raise exception 'Máximo 4 usuarios activos';
  end if;
  return new;
end $$;

create trigger trg_limitar_usuarios
before insert or update on perfiles
for each row execute function limitar_usuarios();

-- ───────── Horarios predefinidos (los defines tú desde la app) ─────────
-- Una franja sirve para etiquetar turnos y para filtrar reportes de yapes.
-- Hora local de Lima. Si hora_fin < hora_inicio, la franja termina al día siguiente.
create table franjas (
  id          bigint generated by default as identity primary key,
  nombre      text not null,
  hora_inicio time not null,
  hora_fin    time not null,
  dias_semana smallint[] not null default '{1,2,3,4,5,6,7}',   -- 1 = lunes … 7 = domingo (por defecto, todos los días)
  activo      boolean not null default true,
  orden       int not null default 0,
  check (hora_inicio <> hora_fin),
  check (cardinality(dias_semana) > 0 and dias_semana <@ '{1,2,3,4,5,6,7}'::smallint[])
);

-- Ajustes editables desde la app
create table ajustes (
  clave text primary key,
  valor text not null
);
insert into ajustes (clave, valor) values ('intervalo_cuadre_min', '30');

-- ───────── Turnos y arqueos de caja ─────────
-- eliminado_at: eliminar = mandar a la papelera (se puede restaurar).
create table turnos (
  id          bigint generated by default as identity primary key,
  cajero_id   uuid references perfiles(id),
  franja_id   bigint references franjas(id) on delete set null,  -- horario predefinido (opcional)
  abierto_at  timestamptz not null default now(),
  cerrado_at  timestamptz,
  estado      text not null default 'abierto' check (estado in ('abierto','cerrado')),
  eliminado_at timestamptz
);
-- Solo un turno abierto a la vez (los de la papelera no cuentan)
create unique index un_turno_abierto on turnos ((true))
  where estado = 'abierto' and eliminado_at is null;

create table arqueos (
  id               bigint generated by default as identity primary key,
  turno_id         bigint not null references turnos(id) on delete cascade,
  tipo             text not null check (tipo in ('inicio','media_hora','cierre')),
  at               timestamptz not null default now(),
  total_contado    numeric(10,2) not null default 0,
  sistema_efectivo numeric(10,2),
  diferencia       numeric(10,2) generated always as (total_contado - sistema_efectivo) stored,
  eliminado_at     timestamptz
);

create table arqueo_detalle (
  arqueo_id    bigint not null references arqueos(id) on delete cascade,
  denominacion numeric(5,2) not null
               check (denominacion in (0.1,0.2,0.5,1,2,5,10,20,50,100)),
  cantidad     int not null default 0 check (cantidad >= 0),
  subtotal     numeric(10,2) generated always as (denominacion * cantidad) stored,
  primary key (arqueo_id, denominacion)
);

-- ───────── Yapes ─────────
-- Todo se puede editar directamente en la base de datos (id incluido).
-- comentario, receptor, emisor y verificacion admiten NULL para integrarlos después.
-- verificacion: NULL = sin revisar, true = verificado, false = no encontrado / falso.
create table yapes (
  id           bigint generated by default as identity primary key,
  monto        numeric(10,2) not null check (monto > 0),
  fecha        timestamptz not null default now(),   -- equivalente a GETDATE()
  comentario   text,
  receptor     text,
  emisor       text,
  verificacion boolean,
  -- extras para las funciones acordadas (se pueden quitar):
  turno_id     bigint references turnos(id),
  orden        numeric,                               -- orden manual; NULL = por fecha
  eliminado_at timestamptz                            -- papelera
);
create index ix_yapes_fecha on yapes (fecha desc);
create index ix_yapes_turno on yapes (turno_id, orden);

-- ───────── Comentarios rápidos ─────────
create table comentarios (
  id           bigint generated by default as identity primary key,
  turno_id     bigint references turnos(id),
  autor_id     uuid references perfiles(id),
  texto        text not null,
  creado_at    timestamptz not null default now(),
  fijado       boolean not null default false,
  hecho        boolean not null default false,
  eliminado_at timestamptz
);

-- ───────── Auditoría ─────────
create table auditoria (
  id          bigint generated by default as identity primary key,
  tabla       text not null,
  registro_id text not null,
  accion      text not null check (accion in ('INSERT','UPDATE','DELETE')),
  usuario_id  uuid,                 -- quién lo hizo (lo informa el backend)
  antes       jsonb,
  despues     jsonb,
  at          timestamptz not null default now()
);
create index ix_auditoria_registro on auditoria (tabla, registro_id);
create index ix_auditoria_at on auditoria (at desc);

-- El backend, al inicio de cada transacción, ejecuta:
--   select set_config('app.usuario_id', '<uuid del usuario>', true);
create function auditar() returns trigger language plpgsql
security definer set search_path = public as $$
declare
  uid uuid := nullif(current_setting('app.usuario_id', true), '')::uuid;
  r   jsonb := case when tg_op = 'DELETE' then to_jsonb(old) else to_jsonb(new) end;
  rid text  := coalesce(r->>'id', concat_ws('-', r->>'arqueo_id', r->>'denominacion'));
begin
  if tg_op = 'INSERT' then
    insert into auditoria(tabla, registro_id, accion, usuario_id, despues)
    values (tg_table_name, rid, tg_op, uid, to_jsonb(new));
  elsif tg_op = 'UPDATE' then
    if to_jsonb(new) is distinct from to_jsonb(old) then
      insert into auditoria(tabla, registro_id, accion, usuario_id, antes, despues)
      values (tg_table_name, rid, tg_op, uid, to_jsonb(old), to_jsonb(new));
    end if;
  else
    insert into auditoria(tabla, registro_id, accion, usuario_id, antes)
    values (tg_table_name, rid, tg_op, uid, to_jsonb(old));
  end if;
  return null;
end $$;

create trigger aud_yapes          after insert or update or delete on yapes          for each row execute function auditar();
create trigger aud_comentarios    after insert or update or delete on comentarios    for each row execute function auditar();
create trigger aud_turnos         after insert or update or delete on turnos         for each row execute function auditar();
create trigger aud_arqueos        after insert or update or delete on arqueos        for each row execute function auditar();
create trigger aud_arqueo_detalle after insert or update or delete on arqueo_detalle for each row execute function auditar();
create trigger aud_perfiles       after insert or update or delete on perfiles       for each row execute function auditar();
create trigger aud_franjas        after insert or update or delete on franjas        for each row execute function auditar();

