-- ───────── Vaciar papelera (solo cuando tú lo ejecutes) ─────────
-- Borra definitivamente lo que lleva más de N días en la papelera.
-- Los turnos se purgan solo si ya no les queda nada asociado.
create function purgar_papelera(dias int default 30) returns void
language sql as $$
  delete from yapes       where eliminado_at < now() - make_interval(days => dias);
  delete from comentarios where eliminado_at < now() - make_interval(days => dias);
  delete from turnos t
   where t.eliminado_at < now() - make_interval(days => dias)
     and not exists (select 1 from yapes y       where y.turno_id = t.id)
     and not exists (select 1 from comentarios c where c.turno_id = t.id);
$$;
